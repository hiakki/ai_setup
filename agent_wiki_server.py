#!/usr/bin/env python3
"""Deploy or inspect the pinned upstream Agent Wiki on one central host."""
import argparse
import json
import os
from pathlib import Path
import re
import secrets
import subprocess
import sys
import time
from urllib.parse import urlsplit
from urllib.request import urlopen


def run(args, **kwargs):
    print('+ ' + ' '.join(map(str, args)), flush=True)
    return subprocess.run(list(map(str, args)), check=True, **kwargs)


def capture(args):
    return subprocess.check_output(list(map(str, args)), text=True, encoding='utf-8').strip()


def validate_public_url(value):
    url = urlsplit(value)
    if (not url.hostname or url.username or url.password or url.query or url.fragment
            or url.path not in ('', '/') or (url.scheme != 'https' and not
            (url.scheme == 'http' and url.hostname in ('localhost', '127.0.0.1', '::1')))):
        raise ValueError('Use an HTTPS public origin without a path, query or credentials; '
                         'HTTP is allowed only for a loopback pilot')
    return value.rstrip('/')


def compose(source):
    result = subprocess.run(['docker', 'compose', 'version'], capture_output=True, text=True)
    if result.returncode != 0:
        raise ValueError('Docker Compose v2 is required and the Docker daemon must be running')
    info = subprocess.run(['docker', 'info'], capture_output=True, text=True)
    if info.returncode != 0:
        raise ValueError('Docker is installed but its daemon is not available')
    if not (source / 'docker-compose.yml').is_file():
        raise ValueError('Pinned Agent Wiki checkout has no docker-compose.yml')
    override = source.parent / 'compose.ai-setup.yml'
    if not override.is_file():
        raise ValueError('Managed Agent Wiki Compose hardening is missing; rerun install')
    return ['docker', 'compose', '--project-directory', str(source),
            '-f', str(source / 'docker-compose.yml'), '-f', str(override)]


def load_config(path):
    data = json.loads(path.read_text(encoding='utf-8'))
    if (not re.fullmatch(r'[0-9a-f]{40}', data.get('revision', ''))
            or data.get('url') != 'https://github.com/onyx-dot-app/agent-wiki.git'):
        raise ValueError('Invalid installed Agent Wiki provider pin')
    return data


def checkout(root, config):
    source = root / 'source'
    if source.exists():
        if not (source / '.git').is_dir():
            raise ValueError('Preserving unmanaged Agent Wiki source directory: ' + str(source))
        if capture(['git', '-C', source, 'remote', 'get-url', 'origin']) != config['url']:
            raise ValueError('Agent Wiki source origin changed; preserving it')
        if capture(['git', '-C', source, 'rev-parse', 'HEAD']) != config['revision']:
            raise ValueError('Agent Wiki source revision differs from the installed pin')
        if capture(['git', '-C', source, 'status', '--porcelain']):
            raise ValueError('Agent Wiki source contains local edits; preserving it')
        return source
    source.parent.mkdir(parents=True, exist_ok=True)
    run(['git', 'init', '-q', source])
    run(['git', '-C', source, 'config', 'core.longpaths', 'true'])
    run(['git', '-C', source, 'remote', 'add', 'origin', config['url']])
    run(['git', '-C', source, 'fetch', '-q', '--depth=1', 'origin', config['revision']])
    run(['git', '-C', source, 'checkout', '-q', '--detach', 'FETCH_HEAD'])
    if capture(['git', '-C', source, 'rev-parse', 'HEAD']) != config['revision']:
        raise ValueError('Fetched Agent Wiki revision mismatch')
    return source


def env_values(path):
    values = {}
    if path.exists():
        for line in path.read_text(encoding='utf-8').splitlines():
            if line and not line.lstrip().startswith('#') and '=' in line:
                key, value = line.split('=', 1)
                values[key] = value
    return values


def configure(source, public_url, port, allowed_emails):
    path = source / '.env'
    existing = env_values(path)
    secure_cookies = 'true' if public_url.startswith('https://') else 'false'
    wanted = {'PUBLIC_BASE_URL': public_url, 'AGENT_WIKI_PORT': str(port),
              'ALLOWED_EMAILS': allowed_emails, 'SECURE_COOKIES': secure_cookies}
    if path.exists():
        for key, value in wanted.items():
            if existing.get(key) != value:
                raise ValueError(f'Existing Agent Wiki .env has a different {key}; review it manually')
        if not existing.get('SECRET_KEY') or existing['SECRET_KEY'] == 'change-me':
            raise ValueError('Existing Agent Wiki .env has no safe SECRET_KEY')
        return
    if public_url.startswith('https://') and not allowed_emails:
        raise ValueError('--allowed-emails is required for a remotely reachable deployment')
    body = ('# Generated by ai_setup. Keep this file private and backed up.\n'
            f'SECRET_KEY={secrets.token_hex(32)}\n'
            f'PUBLIC_BASE_URL={public_url}\n'
            f'AGENT_WIKI_PORT={port}\n'
            f'ALLOWED_EMAILS={allowed_emails}\n'
            f'SECURE_COOKIES={secure_cookies}\n')
    path.write_text(body, encoding='utf-8')
    try:
        path.chmod(0o600)
    except OSError:
        pass


def configure_compose(root):
    """Override upstream development defaults and expose HTTP only on loopback."""
    path = root / 'compose.ai-setup.yml'
    body = '''# Managed by ai_setup. Local reverse proxy terminates HTTPS.
services:
  backend:
    environment:
      DEV_MODE: "false"
      SECURE_COOKIES: "${SECURE_COOKIES:-false}"
  worker-heavy:
    environment:
      DEV_MODE: "false"
  worker-light:
    environment:
      DEV_MODE: "false"
  nginx:
    ports: !override
      - "127.0.0.1:${AGENT_WIKI_PORT:-8090}:80"
'''
    if path.exists() and path.read_text(encoding='utf-8') != body:
        raise ValueError('Existing Agent Wiki Compose hardening differs; review it manually')
    path.write_text(body, encoding='utf-8')
    return path


def wait_until_ready(public_url):
    for _ in range(60):
        try:
            with urlopen(public_url, timeout=5) as response:
                if response.status < 500:
                    return
        except OSError:
            time.sleep(2)
    raise ValueError('Agent Wiki did not respond within two minutes; inspect Docker Compose logs')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', type=Path, default=Path.home() / '.local/share/agent-wiki')
    commands = parser.add_subparsers(dest='command', required=True)
    install = commands.add_parser('install', help='Fetch the pin, generate private config and start the stack')
    install.add_argument('--public-url', default='http://localhost:8090')
    install.add_argument('--port', type=int, default=8090)
    install.add_argument('--allowed-emails', default='')
    commands.add_parser('status')
    commands.add_parser('logs')
    commands.add_parser('stop')
    args = parser.parse_args()
    config = load_config(Path(__file__).with_name('agent-wiki-server.json'))
    source = checkout(args.root.resolve(), config) if args.command == 'install' else args.root.resolve() / 'source'
    if not source.is_dir():
        raise ValueError('Agent Wiki is not installed; run the install command first')
    if args.command == 'install':
        if not 1 <= args.port <= 65535:
            raise ValueError('Port must be between 1 and 65535')
        public_url = validate_public_url(args.public_url)
        configure(source, public_url, args.port, args.allowed_emails)
        configure_compose(args.root.resolve())
        command = compose(source)
        run([*command, 'config', '--quiet'])
        run([*command, '--profile', 'app', 'build'])
        run([*command, '--profile', 'app', 'up', '-d'])
        wait_until_ready(public_url)
        print('Agent Wiki is reachable at', public_url)
        print('Create the first account; it becomes administrator. Then create an individual MCP key.')
        return
    command = compose(source)
    if args.command == 'status':
        run([*command, '--profile', 'app', 'ps'])
    elif args.command == 'logs':
        run([*command, '--profile', 'app', 'logs', '--tail', '200'])
    else:
        run([*command, '--profile', 'app', 'down'])


if __name__ == '__main__':
    try:
        main()
    except (ValueError, OSError, subprocess.CalledProcessError) as exc:
        print('ERROR:', exc, file=sys.stderr)
        sys.exit(1)
